const fs = require("node:fs");
const path = require("node:path");
const { gzipSync } = require("node:zlib");

const source = path.join(__dirname, "전국주유소표준데이터", "HangJeongDong_ver20261001.geojson");
const output = path.join(__dirname, "boundaries");
const { features } = JSON.parse(fs.readFileSync(source, "utf8"));
const provinces = new Map();

for (const { properties, geometry } of features) {
  const { sido, sidonm, sggnm } = properties;
  if (!/^\d{2}$/.test(sido) || !sidonm || !sggnm) throw new Error("Invalid boundary region");
  if (!provinces.has(sido)) provinces.set(sido, { name: sidonm, features: [] });
  const province = provinces.get(sido);
  if (province.name !== sidonm) throw new Error("Conflicting province code " + sido);
  province.features.push({ type: "Feature", properties: { sidonm, sggnm }, geometry });
}

fs.mkdirSync(output, { recursive: true });
const entries = [];
for (const [code, province] of provinces) {
  const collection = JSON.stringify({ type: "FeatureCollection", features: province.features });
  fs.writeFileSync(path.join(output, code + ".gz"), gzipSync(collection));
  entries.push([province.name, code]);
}
fs.writeFileSync(path.join(output, "index.js"),
  "// Generated by build-boundaries.cjs.\nconst boundaryCodes = new Map(" + JSON.stringify(entries) + ");\n");
